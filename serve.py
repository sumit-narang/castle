#!/usr/bin/env python3
"""Dev server for the Castles of Ireland web UI.

Reads your Mapbox token from `.env`, writes it into `web/config.js`, then serves
the project over HTTP so the page can fetch the data files.

    python3 serve.py            # build config + serve on http://localhost:8765
    python3 serve.py --build    # just (re)generate web/config.js, don't serve

NOTE: Mapbox is a client-side library, so the token is sent to the browser no
matter what — `.env` only keeps it out of your source tree. Protect it by adding
a URL restriction to the token in your Mapbox dashboard.
"""

from __future__ import annotations

import http.server
import json
import socketserver
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ENV_PATH = ROOT / ".env"
CONFIG_PATH = ROOT / "web" / "config.js"
PORT = 8765

DEFAULT_STYLE = "mapbox://styles/mapbox/outdoors-v12"


def load_env(path: Path) -> dict[str, str]:
    """Minimal .env parser: KEY=VALUE lines, ignoring blanks and # comments."""
    env: dict[str, str] = {}
    if not path.exists():
        return env
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        env[key.strip()] = value.strip().strip('"').strip("'")
    return env


def build_config() -> str:
    env = load_env(ENV_PATH)
    token = env.get("MAPBOX_TOKEN", "")
    style = env.get("MAP_STYLE") or DEFAULT_STYLE

    if not token or token == "pk.your_public_token_here":
        print("  ! No real MAPBOX_TOKEN found in .env — the map won't render.")
        print("    Add your public token (pk.…) to .env, then re-run.")

    # config.js is generated; values are JSON-encoded so quotes/escaping are safe.
    CONFIG_PATH.write_text(
        "// AUTO-GENERATED by serve.py from .env — do not edit by hand.\n"
        "window.APP_CONFIG = {\n"
        f"  MAPBOX_TOKEN: {json.dumps(token)},\n"
        f"  MAP_STYLE: {json.dumps(style)},\n"
        "};\n",
        encoding="utf-8",
    )
    print(f"  wrote {CONFIG_PATH.relative_to(ROOT)}")
    return token


class NoCacheHandler(http.server.SimpleHTTPRequestHandler):
    """Serve files with caching switched off.

    SimpleHTTPRequestHandler sends only Last-Modified, so browsers fall back to
    heuristic caching and reuse app.js / style.css from disk without asking the
    server — which means an edit doesn't show up on reload. For a dev server we
    always want the current file.
    """

    def end_headers(self) -> None:
        self.send_header("Cache-Control", "no-store, no-cache, must-revalidate")
        self.send_header("Expires", "0")
        super().end_headers()


def serve() -> None:
    handler = NoCacheHandler
    socketserver.TCPServer.allow_reuse_address = True
    with socketserver.TCPServer(("", PORT), handler) as httpd:
        url = f"http://localhost:{PORT}/web/index.html"
        print(f"\n  Serving {ROOT} at {url}\n  Press Ctrl+C to stop.")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\n  Stopped.")


if __name__ == "__main__":
    print("Building web/config.js from .env...")
    build_config()
    if "--build" not in sys.argv:
        serve()
